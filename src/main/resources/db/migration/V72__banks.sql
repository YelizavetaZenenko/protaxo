-- МФО унікальне: за ним банк визначається з IBAN (цифри 5–10 IBAN = МФО).
CREATE TABLE banks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    mfo        VARCHAR(6),
    edrpou     VARCHAR(8),
    source     VARCHAR(10) NOT NULL DEFAULT 'NBU',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_banks_mfo ON banks (mfo) WHERE mfo IS NOT NULL;
CREATE UNIQUE INDEX ux_banks_name ON banks (lower(name));

