-- Календар записів клієнтів (docs/Календар.md): дата й час, тривалість, контрагент з довідника
-- (client_id) або просто ім'я того, хто ще не в довіднику (client_name завжди заповнене).
CREATE TABLE appointments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    starts_at        TIMESTAMP    NOT NULL,
    duration_minutes INTEGER      NOT NULL DEFAULT 60 CHECK (duration_minutes BETWEEN 5 AND 720),
    client_id        BIGINT REFERENCES clients (id) ON DELETE SET NULL,
    client_name      VARCHAR(255) NOT NULL,
    phone            VARCHAR(32),
    vehicle          VARCHAR(255),
    note             VARCHAR(2000),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_appointments_starts_at ON appointments (starts_at);
