-- Підкатегорії товарів каталогу (docs/Каталог.md): довідник, який можна поповнювати з форми товару.
-- Послуги категорій не мають. Плюс нові товари з прайсів користувачки (2026-11-22):
--  * два фото прайсу — ціна продажу (base_price);
--  * третє фото (червона колонка) — ціна ЗАКУПІВЛІ, ціну продажу поки 0 — вкажуть у каталозі;
--  * тахограф VDO новий 515–570 € → 570 € × 49,2763 (курс НБУ на 23.11.2026) ≈ 28 090 грн;
--  * позиції з ціною 0 у прайсі додані з 0 за рішенням користувачки.
-- Залишок NULL — склад для нових позицій не ведеться, поки його не внесуть (ревізія/закупівля),
-- інакше наряд не дав би їх продати («Недостатньо на складі»).

CREATE TABLE catalog_categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_catalog_categories_name ON catalog_categories (lower(name));

ALTER TABLE catalog_items ADD COLUMN category_id BIGINT REFERENCES catalog_categories (id);
CREATE INDEX idx_catalog_items_category ON catalog_items (category_id);

