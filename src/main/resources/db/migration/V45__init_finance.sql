-- ---------------------------------------------------------------- Звірки
CREATE TABLE finance_reconciliations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT NOT NULL REFERENCES finance_accounts(id),
    counted_at          TIMESTAMPTZ NOT NULL,
    expected_balance    NUMERIC(14,2) NOT NULL,
    actual_balance      NUMERIC(14,2) NOT NULL,
    difference          NUMERIC(14,2) NOT NULL,
    status              VARCHAR(20) NOT NULL,
    comment             TEXT,
    created_by          VARCHAR(255) NOT NULL,
    resolved_at         TIMESTAMPTZ,
    resolved_by         VARCHAR(255),
    resolution_comment  TEXT,
    version             BIGINT NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ,
    deleted_at          TIMESTAMPTZ
);

CREATE INDEX idx_finance_reconciliations_status ON finance_reconciliations (status);

-- ---------------------------------------------------------------- Операції
-- Один журнал для всіх рухів коштів: оплата, повернення, витрата, переміщення, внесення/
-- вилучення власником, коригування за звіркою. amount завжди > 0, напрям визначається типом.
-- Проведені операції не видаляються: скасування (сторно) ставить cancelled_* з причиною,
-- і операція перестає впливати на залишки й борги, але лишається в історії.
CREATE TABLE finance_operations (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                   VARCHAR(30) NOT NULL,
    account_id             BIGINT NOT NULL REFERENCES finance_accounts(id),
    target_account_id      BIGINT REFERENCES finance_accounts(id),
    amount                 NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    payment_method         VARCHAR(20),
    invoice_id             BIGINT REFERENCES invoices(id),
    original_operation_id  BIGINT REFERENCES finance_operations(id),
    reconciliation_id      BIGINT REFERENCES finance_reconciliations(id),
    received_amount        NUMERIC(14,2),
    change_amount          NUMERIC(14,2),
    refund_kind            VARCHAR(30),
    expense_category       VARCHAR(30),
    counterparty           VARCHAR(255),
    document_ref           VARCHAR(255),
    comment                TEXT,
    occurred_at            TIMESTAMPTZ NOT NULL,
    created_by             VARCHAR(255) NOT NULL,
    request_key            VARCHAR(64) NOT NULL UNIQUE,
    cancelled_at           TIMESTAMPTZ,
    cancelled_by           VARCHAR(255),
    cancel_reason          TEXT,
    version                BIGINT NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ,
    deleted_at             TIMESTAMPTZ
);

CREATE INDEX idx_finance_operations_invoice_id ON finance_operations (invoice_id);
CREATE INDEX idx_finance_operations_account_id ON finance_operations (account_id);
CREATE INDEX idx_finance_operations_occurred_at ON finance_operations (occurred_at DESC);
CREATE INDEX idx_finance_operations_original ON finance_operations (original_operation_id);

-- Підтвердний документ до витрати (скан чека, накладна). Окрема таблиця, щоб байти файлу
-- не вантажились разом з кожною операцією в списках.
CREATE TABLE finance_attachments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id   BIGINT NOT NULL REFERENCES finance_operations(id),
    file_name      VARCHAR(255) NOT NULL,
    content_type   VARCHAR(100) NOT NULL,
    size_bytes     BIGINT NOT NULL,
    data           BYTEA NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_finance_attachments_operation_id ON finance_attachments (operation_id);
