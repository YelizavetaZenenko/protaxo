-- Існуючі рядки: те саме правило, що досі застосовувалось лише під час друку PDF рахунку
-- (20/120 від суми рядка, HALF_UP до копійок) — ROUND у Postgres для numeric округлює
-- половину від нуля, для додатних сум це HALF_UP.
UPDATE invoice_items SET vat_amount = ROUND(amount * 20 / 120, 2);
UPDATE invoice_items SET amount_without_vat = amount - vat_amount;
ALTER TABLE invoice_items ALTER COLUMN vat_amount SET NOT NULL;
ALTER TABLE invoice_items ALTER COLUMN amount_without_vat SET NOT NULL;

