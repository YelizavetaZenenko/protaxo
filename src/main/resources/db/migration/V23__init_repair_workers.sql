CREATE TABLE repair_workers (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    position  VARCHAR(255) NOT NULL
);

-- Migrate previously free-typed "Відповідальний за ремонт"/"Керівник ремонту" values into the
-- new structured directory, so nothing already typed by users is lost. They have no recorded
-- position — flagged with a placeholder that an admin can correct later.
INSERT INTO repair_workers (full_name, position)
SELECT DISTINCT value, '(не вказано)'
FROM field_suggestions
WHERE category IN ('REPAIR_RESPONSIBLE', 'REPAIR_SUPERVISOR');

DELETE FROM field_suggestions WHERE category IN ('REPAIR_RESPONSIBLE', 'REPAIR_SUPERVISOR');

-- DRIVER suggestions became dead data once "Водій" switched to the real Driver directory
-- (see [[Наряд-заказ]], per-client driver picker) — nothing reads this category anymore.
DELETE FROM field_suggestions WHERE category = 'DRIVER';
